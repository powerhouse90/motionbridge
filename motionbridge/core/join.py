"""Join two SOMA motions with a generated transition (NVIDIA MotionBricks), or loop one back to its start.

MotionBricks takes the last four poses of where the body is (context) and four poses of where it should go
(target), at 30 Hz, and generates the motion between them on the same SOMA skeleton GEM reads (same joints,
order and joint frames; only bone lengths differ, so rotations pass straight through and the hips' height is
scaled by leg length). It predicts the body; fingers, eyes and jaw are blended from A's last pose to B's first.
B is moved and turned (about the vertical) to start where A ends, so the character doesn't jump. The runner
(bricks/runner.py) runs in MotionBricks' own Python; this side is numpy only."""
import json
import subprocess
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation, Slerp

from motionbridge.core import contacts
from motionbridge.core.soma import SomaMotion

RATE = 30.0         # MotionBricks' sample rate
POSES = 4           # poses per context, target and token
SKIP = ('Thumb', 'Index', 'Middle', 'Ring', 'Pinky', 'Jaw', 'Eye', 'HeadEnd', 'ToeEnd')  # not predicted: blended
UP = np.array([0.0, 1.0, 0.0])
MOVING = 0.2       # m/s of hips travel at a seam that counts as moving (a slow walk is ~0.8)
STRIDE = 0.8       # s: transition length when moving and none is given, about one walking step


def sample(world, fps, times):
    """World matrices (n, J, 4, 4) of a motion's frames at times (s): rotations slerped, positions lerped."""
    T = len(world)
    f = np.clip(np.asarray(times) * fps, 0, T - 1)
    out = np.empty((len(f),) + world.shape[1:])
    for j in range(world.shape[1]):
        if T == 1:
            out[:, j] = world[0, j]
            continue
        slerp = Slerp(np.arange(T), Rotation.from_matrix(world[:, j, :3, :3]))
        out[:, j] = np.eye(4)
        out[:, j, :3, :3] = slerp(f).as_matrix()
        out[:, j, :3, 3] = np.array([np.interp(f, np.arange(T), world[:, j, :3, 3][:, k]) for k in range(3)]).T
    return out


def local_quats(world, parents):
    """Local rotations (n, J-1, 4) XYZW of joints 1.. (the hips' is its world rotation; Root is static)."""
    out = np.empty((len(world), len(parents) - 1, 4))
    for j in range(1, len(parents)):
        p = parents[j]
        R = world[:, j, :3, :3] if p <= 0 else np.linalg.inv(world[:, p, :3, :3]) @ world[:, j, :3, :3]
        out[:, j - 1] = Rotation.from_matrix(R).as_quat()
    return out


def facing(world, names):
    """Ground placement of one frame: hips position on the floor plane and yaw (rad) of the hips' left->right."""
    h, l, r = names.index('Hips'), names.index('LeftLeg'), names.index('RightLeg')
    across = world[r, :3, 3] - world[l, :3, 3]
    fwd = np.cross(across, UP)
    return world[h, :3, 3] * [1, 0, 1], np.arctan2(fwd[0], fwd[2])


def ground_velocity(world, names, fps):
    """Hips' mean velocity along the floor (m/s) over these frames."""
    h = world[:, names.index('Hips'), :3, 3] * [1, 0, 1]
    return (h[-1] - h[0]) * fps / max(len(h) - 1, 1)


def placed(world, names, to):
    """world (n, J, 4, 4) moved and turned about the vertical so its first frame stands like `to` (one frame).
    Root stays put (see join)."""
    (p0, y0), (p1, y1) = facing(world[0], names), facing(to, names)
    R = np.eye(4)
    R[:3, :3] = Rotation.from_rotvec(UP * (y1 - y0)).as_matrix()
    M = np.eye(4)
    M[:3, 3] = p1
    M = M @ R
    M[:3, 3] -= (R[:3, :3] @ p0)
    out = np.einsum('ab,njbc->njac', M, world)
    out[:, 0] = world[:, 0]
    return out


def leg_length(rest, names):
    i = names.index
    return np.linalg.norm(rest[i('LeftShin'), :3, 3] - rest[i('LeftLeg'), :3, 3]) + \
        np.linalg.norm(rest[i('LeftFoot'), :3, 3] - rest[i('LeftShin'), :3, 3])


def transition(a, b_world, python, repo, folder, seconds=0.0, log=None):
    """World matrices (n, J, 4, 4) at a.fps strictly between a's last frame and b_world's first (placed already),
    generated by MotionBricks. seconds: 0 lets the model choose (about 1-1.7 s), else 0.6-1.9."""
    names = list(a.names)
    end = (a.frames - 1) / a.fps
    ctx = sample(a.world, a.fps, end - np.arange(POSES)[::-1] / RATE)
    tgt = sample(b_world, a.fps, np.arange(POSES) / RATE)
    both = np.concatenate([ctx, tgt])
    gem_leg = leg_length(a.rest, names)
    MB_LEG = 0.8573  # MotionBricks' SOMA thigh + shin (0.433 + 0.424 m)
    s = MB_LEG / gem_leg
    floor = contacts.ground_track(a)[-1]  # MotionBricks stands on y = 0; GEM's floor drifts
    lift = np.array([0.0, floor, 0.0])
    tokens = 0 if not seconds else int(np.clip(round((seconds * RATE + 6) / POSES), 6, 16))
    folder.mkdir(parents=True, exist_ok=True)
    inp, out = (folder / 'bricks_in.npz').resolve(), (folder / 'bricks_out.npz').resolve()
    np.savez(inp, rotations=local_quats(both, a.parents).astype(np.float32),
             hips=((both[:, names.index('Hips'), :3, 3] - lift) * s).astype(np.float32), tokens=tokens)
    runner = Path(__file__).resolve().parents[1] / 'bricks' / 'runner.py'
    r = subprocess.run([str(python), str(runner), '--repo', str(repo), '--inp', str(inp), '--out', str(out)],
                       capture_output=True, text=True)
    if r.returncode or not out.exists():
        raise RuntimeError('MotionBricks failed:\n' + (r.stdout + r.stderr)[-3000:])
    if log:
        log(next((l for l in r.stdout.splitlines() if 'MOTIONBRICKS' in l), r.stdout[-300:]))
    g = np.load(out)
    n = len(g['rotations'])
    # back to GEM: predicted joints' local rotations on GEM's own bone offsets, the hips unscaled
    first, last = both[POSES - 1], both[POSES]
    # bone offsets ease from a's to b's: takes differ in body scale (two-view refinement fits one per take)
    offsets = [np.array([np.linalg.inv(f[p]) @ f[j] if p > 0 else np.eye(4) for j, p in enumerate(a.parents)])[:, :3, 3]
               for f in (first, last)]
    blend = [j for j in range(1, len(names)) if any(k in names[j] for k in SKIP)]
    q0, q1 = local_quats(first[None], a.parents)[0], local_quats(last[None], a.parents)[0]
    # MotionBricks poses its own proportions, so its ends miss a's last and b's first pose by a little (legs a few
    # degrees, feet ~2 cm), a pop at each seam. Each end's leftover is spread across the transition (offset blending)
    rots = Rotation.from_quat(g['rotations'].reshape(-1, 4).astype(np.float64))
    rots = rots.as_quat().reshape(g['rotations'].shape)
    miss = [Rotation.from_quat(q) * Rotation.from_quat(rots[k]).inv() for q, k in ((q0, 0), (q1, -1))]
    hips = g['hips'].astype(np.float64) / s + lift
    hips_miss = first[names.index('Hips'), :3, 3] - hips[0], last[names.index('Hips'), :3, 3] - hips[-1]
    gen = np.empty((n, len(names), 4, 4))
    for t in range(n):
        u = t / max(n - 1, 1)
        fix = [Slerp([0, 1], Rotation.concatenate([miss[0][j], miss[1][j]]))(u) for j in range(len(names) - 1)]
        rot = np.array([(fix[j] * Rotation.from_quat(rots[t, j])).as_quat() for j in range(len(names) - 1)])
        for j in blend:
            rot[j - 1] = Slerp([0, 1], Rotation.from_quat([q0[j - 1], q1[j - 1]]))(u).as_quat()
        gen[t, 0] = first[0]  # Root: GEM's fixed origin
        for j in range(1, len(names)):
            L = np.eye(4)
            L[:3, :3] = Rotation.from_quat(rot[j - 1]).as_matrix()
            if a.parents[j] <= 0:
                L[:3, 3] = hips[t] + (1 - u) * hips_miss[0] + u * hips_miss[1]
                gen[t, j] = L
            else:
                L[:3, 3] = (1 - u) * offsets[0][j] + u * offsets[1][j]
                gen[t, j] = gen[t, a.parents[j]] @ L
    # resample from 30 Hz to the motion's rate, without the two ends (they are a's last and b's first frames)
    times = np.arange(1, int(np.floor((n - 1) / RATE * a.fps))) / a.fps
    return sample(gen, RATE, times) if len(times) else gen[1:1]


def join(a, b, python, repo, folder, seconds=0.0, keep_place=False, log=None):
    """(SomaMotion, generated frame count, place). The motion is a, the generated transition, then b (moved to start
    where a ends unless keep_place). b None loops a: the transition runs from a's end back to a's own first pose,
    and the next cycle starts there. place: the (4, 4) transform that put b (or the next cycle) where it starts."""
    names = list(a.names)
    b_world = (a if b is None else b).world
    source = b_world
    if not keep_place:
        b_world = placed(b_world, names, a.world[-1])
        # Moving at the seam (a walk, a run): b starts ahead by the ground the transition covers at that speed, or
        # MotionBricks has to bring the body back to where it was and the walk stops
        speed = (ground_velocity(a.world[-POSES:], names, a.fps) + ground_velocity(b_world[:POSES], names, a.fps)) / 2
        if np.linalg.norm(speed) > MOVING:
            seconds = seconds or STRIDE
            b_world = b_world.copy()
            b_world[:, 1:, :3, 3] += speed * seconds
            if log:
                log(f'moving at {np.linalg.norm(speed):.2f} m/s: {seconds:g} s transition, b starts {np.linalg.norm(speed) * seconds:.2f} m on')
    # one Root for the whole clip, a's (two-view refinement offsets it per take): smoothing and the retarget read
    # the hips relative to it, so a change at the seam jolts the whole body
    b_world = b_world.copy()
    b_world[:, 0] = a.world[-1, 0]
    mid = transition(a, b_world, python, repo, folder, seconds, log)
    world = np.concatenate([a.world, mid] + ([] if b is None else [b_world]))
    if log:
        log(f'joined: {a.frames} + {len(mid)} generated + {0 if b is None else len(b_world)} frames at {a.fps:g} fps')
    place = b_world[0, names.index('Hips')] @ np.linalg.inv(source[0, names.index('Hips')])
    return SomaMotion(a.names, a.parents, world, a.rest, a.fps, a.source + ' +join'), len(mid), place
